import { useCallback, useRef } from 'react';

/**
 * Ушли ли со страницы, на которой запущена покадровая анимация.
 *
 * React Router 7 рисует новую страницу переходом (startTransition) — это
 * низкий приоритет, и любое обычное обновление состояния его перебивает.
 * Шар, который вращается сам, обновляет состояние каждый кадр, и переход
 * на «Главную» не доходил до экрана никогда: адрес уже «/», а на экране
 * всё ещё глобус. Поэтому вращение, перелёт к месту и проигрывание истории
 * сверяются с адресом и останавливаются сами, как только он сменился, —
 * не дожидаясь, пока React снимет компонент.
 */
export function useLeftPage(): () => boolean {
  const path = useRef(window.location.pathname);
  return useCallback(() => window.location.pathname !== path.current, []);
}
